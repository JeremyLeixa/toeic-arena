// Mimic Hunt — 84 items (29 / 30 / 25 par palier) : 12 pilotes (2026-09-17) + 48 rédigés le 2026-09-18/19 et
// relus par Jérémy (mh13-mh60) + le lot 4 « parlé » (mh61-mh84, 2026-09-19, relu) : 45 sources `spoken`.
// Proto : prototypes/mimic-hunt/ ; relecture : prototypes/mimic-hunt/review.html.
//
// Un Mimic = une option qui RECOPIE des mots de la source pour dire autre chose qu'elle.
// La bonne réponse dit la même chose avec d'autres mots (le pont).
//
// Format :
//   ctx      étiquette du document (email, annonce, conversation…)
//   speaker  locuteur affiché devant la réplique (facultatif)
//   src      le texte source            q  la question (style TOEIC)
//   opts     4 options                  c  index de la bonne réponse
//   bridge   [[dans la source, dans la bonne réponse], …] : ce qui a été reformulé
//   echo     mots gardés tels quels par la bonne réponse (faute de synonyme courant)
//   mimics   {index: [fragment | [dans la source, dans l'option]], …} : ce que le Mimic recopie
//   exp      pourquoi la bonne réponse est juste     trap  ce que les Mimics ont recopié
//   spoken   la source SE DIT (conversation, messagerie, annonce…) : elle sert aussi au mode écoute, lue par
//            une voix de lib/listeningVoices.js (mimicVoice) dans /audio/mimic/<id>.mp3 (2026-09-19). Un e-mail
//            ou une notice lus à voix haute ne ressemblent à rien du TOEIC : pas de `spoken`.
//   voice    "m" | "f" quand la source parlée se présente (« Hi, it's Dana… ») : la voix suit ce genre
//            (sinon `speaker` Man / Woman, sinon l'une des six)
//
// Fragments : sans casse, en mots entiers. tests/check_mimic_items.cjs vérifie que chacun se
// trouve bien là où il est annoncé — sinon le surlignage disparaît en silence, et avec lui la leçon.
// Les options sont permutées à chaque partie : aucun texte ne cite une option par sa lettre (les pièges
// citent l'option elle-même ; tests/check_option_shuffle.cjs le vérifie).
//
// Équilibre : bonne réponse 21 fois en A, B, C et D ; 2 Mimics par item sauf cinq (mh04, mh11, mh21,
// mh40, mh50 : un seul, sinon « 2 Mimics + 1 neutre » devient un patron qu'on joue sans lire) ; cinq items
// gardent un mot de la source DANS la bonne réponse (mh12, mh18, mh22, mh35, mh59, et mh72 au lot 4), pour casser la règle
// trop simple « mot repris = faux ». Palier II : plusieurs Mimics recopient presque tout et ne changent
// qu'un rôle ou une négation (mh38, mh44).

